QStringList Tips::sections() {
    QStringList out;
    for (const Tip& t : all())
        if (!out.contains(t.section)) out << t.section;
    return out;
}

Tips::Tip Tips::get(const QString& id) {
    for (const Tip& t : all())
        if (t.id == id) return t;
    return Tip{};
}

QList<Tips::Tip> Tips::find(const QString& query) {
    const QStringList words = query.simplified().split(' ', Qt::SkipEmptyParts);
    QList<Tip> out;
    for (const Tip& t : all()) {
        const QString hay = t.section + ' ' + t.title + ' ' + t.text;
        bool ok = true;
        for (const QString& w : words) ok = ok && hay.contains(w, Qt::CaseInsensitive);
        if (ok) out << t;
    }
    return out;
}

bool Tips::badges() { return AppSettings::open()->value("tips/badges", true).toBool(); }
void Tips::setBadges(bool on) { auto s = AppSettings::open(); s->setValue("tips/badges", on); s->sync(); }
bool Tips::firstTime() { return AppSettings::open()->value("tips/firstTime", true).toBool(); }
void Tips::setFirstTime(bool on) { auto s = AppSettings::open(); s->setValue("tips/firstTime", on); s->sync(); }

bool Tips::seen(const QString& id) { return AppSettings::open()->value("tips/seen").toStringList().contains(id); }
int Tips::seenCount() { return int(AppSettings::open()->value("tips/seen").toStringList().size()); }

bool Tips::takeFirstTime(const QString& id) {
    if (get(id).isNull()) return false;
    auto s = AppSettings::open();
    QStringList seenIds = s->value("tips/seen").toStringList();
    if (seenIds.contains(id)) return false;
    seenIds << id;                   // и когда выключены: включил позже — старое не всплывёт
    s->setValue("tips/seen", seenIds);
    s->sync();
    return s->value("tips/firstTime", true).toBool();
}

void Tips::resetSeen() { auto s = AppSettings::open(); s->remove("tips/seen"); s->sync(); }
