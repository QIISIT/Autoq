#pragma once
// Окно группы действий: имя и что в ней (тот же ряд карточек, что в «Действиях»).
// Группы общие для всех игр: правка меняет группу везде, где она стоит.
// Вид группы — действия (клик / держать) или шаги (нажать ↓ / отпустить ↑): переключатель
// вверху раскладывает каждое действие на «нажать» и «отпустить» и собирает обратно.
#include "games.h"

class QWidget;

namespace GroupDialog {
enum Result { Cancelled, Saved, Deleted, DeletedWithCards };
// uses — сколько раз группа стоит в текущем ряду; isNew — новая («Создать группу…»,
// без «Удалить»); stepsRow — открыли из ряда «По шагам»: группа из действий сразу
// показывается шагами (каждая клавиша — отдельно «нажать» и «отпустить»)
Result edit(QWidget* parent, ActionGroup& g, int uses, bool isNew = false, bool stepsRow = false);
// «Удалить группу?»: Deleted — её карточки в ряду станут обычными действиями,
// DeletedWithCards — пропадут из ряда вместе с ней, Cancelled — не удалять.
// В других играх её карточки в любом случае становятся обычными действиями
Result askDelete(QWidget* parent, const ActionGroup& g, int uses);
}
